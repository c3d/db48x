LCD_Status_t Disp_Init(LCD_Handle_t *p_hlcd)
{
   if (!p_hlcd) return LCD_ERROR;


#if ((SHARP_27_400x240 | SHARP_32_536x336))

//   SHARP_SPI_Init(   p_hlcd);
   LCD_Sharp_Init(   p_hlcd, true);
   p_hlcd->use_ltsc = false;

#elif TFT_LTDC
   p_hlcd->use_ltsc = true;
   LTDC_Init(p_hlcd);
#elif LCD_ST7796_480x320 
   p_hlcd->use_ltsc = false;

#endif
   p_hlcd->modified.x_min = LCD_WIDTH-1;
   p_hlcd->modified.y_min = LCD_HEIGHT-1;
   p_hlcd->modified.x_max = 0;
   p_hlcd->modified.y_max = 0;

   p_hlcd->initialized = true;
   p_hlcd->p_RamDb48x = &_db48xVRAM[0];
   p_hlcd->p_Vram = &_aVRAM[0];
   return p_hlcd->status;
}


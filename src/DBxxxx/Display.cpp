LCD_Status_t Disp_SetPixel(LCD_Handle_t *p_hlcd, uint16_t x, uint16_t y, int32_t pixel)
{
    if (!p_hlcd || !p_hlcd->initialized || x >= LCD_WIDTH || y >= LCD_HEIGHT) {
        return LCD_ERROR;
    }

#if (SHARP_27_400x240 | SHARP_32_536x336)
   LCD_SetPixel(p_hlcd, x, y, pixel);
#elif TFT_LTDC
   int32_t tmp_pix = pixel>0 ? 0x07c0 : pixel;
   LTDC_SetPixel( x, y, tmp_pix);
#elif LCD_ST7796_480x320 

#endif
   if ( p_hlcd->modified.x_min > x ) p_hlcd->modified.x_min = x ;
   if ( p_hlcd->modified.x_max < x ) p_hlcd->modified.x_max = x;

   if ( p_hlcd->modified.y_min > y ) p_hlcd->modified.y_min = y;
   if ( p_hlcd->modified.y_max < y ) p_hlcd->modified.y_max = y;
   return LCD_OK;
}


void LCD_MarkLineModified(LCD_Handle_t *p_hlcd, uint16_t x_min, uint16_t y_min, uint16_t x_max, uint16_t y_max)
{
   if ( x_max >= LCD_WIDTH) x_max = LCD_WIDTH - 1;
   if ( y_max >= LCD_HEIGHT) y_max = LCD_HEIGHT - 1; 
   if ( !p_hlcd 
         || !p_hlcd->initialized 
         || x_max >=LCD_WIDTH
         || x_min > x_max
         || y_min > y_max
         || y_max > LCD_HEIGHT)
   {
        return;
   }
   if ( p_hlcd->modified.x_min > x_min ) p_hlcd->modified.x_min = x_min ;
   if ( p_hlcd->modified.x_max < x_max ) p_hlcd->modified.x_max = x_max;

   if ( p_hlcd->modified.y_min > y_min ) p_hlcd->modified.y_min = y_min;
   if ( p_hlcd->modified.y_max < y_max ) p_hlcd->modified.y_max =  y_max;

}


/**
 * @brief Draw a segment using Bresenham's algorithm
 * @param hlcd: LCD handle
 * @param x0, y0 : coordinates of first point
 * @param x1, y1 : coordinates of second point
 * @param pixel: Pixel state (1 = black, 0 = white, -1 = toggle)
 * @retval LCD_Status_t
 */
void LCD_DrawLine(LCD_Handle_t *hlcd,uint16_t x0, uint16_t y0, uint16_t x1, uint16_t y1, int8_t pixel) 
{
    int16_t dx = abs(x1 - x0);
    int16_t dy = abs(y1 - y0);
    int16_t sx = (x0 < x1) ? 1 : -1;
    int16_t sy = (y0 < y1) ? 1 : -1;
    int16_t err = dx - dy;
    
    while (1) {
        Disp_SetPixel(hlcd, x0, y0, pixel);
        
        if (x0 == x1 && y0 == y1) break;
        
        int16_t e2 = 2 * err;
        if (e2 > -dy) {
            err -= dy;
            x0 += sx;
        }
        if (e2 < dx) {
            err += dx;
            y0 += sy;
        }
    }
}

/**
 * @brief Fill a rectangle in the framebuffer
 * @param hlcd: LCD handle
 * @param x: X coordinate of top-left corner
 * @param y: Y coordinate of top-left corner
 * @param w: Width in pixels
 * @param h: Height in pixels
 * @param pixel: Pixel state (1 = black, 0 = white, -1 = toggle)
 * @retval LCD_Status_t
 */
LCD_Status_t LCD_FillRect(LCD_Handle_t *hlcd, uint16_t x, uint16_t y, uint16_t w, uint16_t h, int8_t pixel)
{
    if (!hlcd || !hlcd->initialized) {
        return LCD_ERROR;
    }

   

    /* Clip rectangle to display bounds */
    if (x >= LCD_WIDTH || y >= LCD_HEIGHT) {
        return LCD_OK;
    }
    if (x + w > LCD_WIDTH) {
        w = LCD_WIDTH - x;
    }
    if (y + h > LCD_HEIGHT) {
        h = LCD_HEIGHT - y;
    }

    for (uint16_t dy = 0; dy < h; dy++) {
       LCD_DrawLine(hlcd, x, y+dy, x + w - 1, y+dy, pixel);              // Top

   }
   return LCD_OK;
}


/**
 * @brief Draw a rectangle in the framebuffer
 * @param hlcd: LCD handle
 * @param x: X coordinate of top-left corner
 * @param y: Y coordinate of top-left corner
 * @param w: Width in pixels
 * @param h: Height in pixels
 * @param pixel: Pixel state (1 = black, 0 = white, -1 = toggle)
 * @retval LCD_Status_t
 */
// Draw rectangle outline
void LCD_DrawRect(LCD_Handle_t *hlcd, uint16_t x, uint16_t y, uint16_t w, uint16_t h, int8_t pixel) 
{
    LCD_DrawLine(hlcd, x, y, x + w - 1, y, pixel);                      // Top
    LCD_DrawLine(hlcd, x, y + h - 1, x + w - 1, y + h - 1, pixel);      // Bottom
    LCD_DrawLine(hlcd, x, y, x, y + h - 1, pixel);                      // Left
    LCD_DrawLine(hlcd, x + w - 1, y, x + w - 1, y + h - 1, pixel);      // Right
}

LCD_Status_t Disp_Update(LCD_Handle_t *p_hlcd, bool force_full_redraw, bool wait_for_dma_end)
{
   if (!p_hlcd) return LCD_ERROR;
   if (force_full_redraw){
      p_hlcd->modified.x_min = 0;
      p_hlcd->modified.y_min = 0;
      p_hlcd->modified.x_max = LCD_WIDTH-1;
      p_hlcd->modified.y_max = LCD_HEIGHT-1;
   }
#if (SHARP_27_400x240 | SHARP_32_536x336)
   /* return from sleeping with spi & dma clocks off */
   if (true == p_hlcd->spi_off)    SHARP_SPI_Init(p_hlcd);
   SPI_UpdateModifiedLines(p_hlcd);
#elif TFT_LTDC
   CopyRegionToVRAM( p_hlcd->modified.x_min, p_hlcd->modified.x_max, p_hlcd->modified.y_min, p_hlcd->modified.y_max);
#elif LCD_ST7796_480x320 

#endif
   p_hlcd->modified.x_min = LCD_WIDTH-1;
   p_hlcd->modified.y_min = LCD_HEIGHT-1;
   p_hlcd->modified.x_max = 0;
   p_hlcd->modified.y_max = 0;

   if (wait_for_dma_end)   Disp_WaitForTransfer(p_hlcd);
   return LCD_OK;
}



